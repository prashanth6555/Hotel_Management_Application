function finalize(hotel) {
  return {
    ...hotel,
    priceFrom: Math.min(...hotel.rooms.map((room) => room.price)),
  };
}

export const hotels = hotelsRaw.map(finalize);

export const locationSuggestions = [
  ...new Set(hotels.flatMap((hotel) => [hotel.city, hotel.country, hotel.region])),
].sort((a, b) => a.localeCompare(b));

export const destinations = hotels.map((hotel) => ({
  city: hotel.city,
  country: hotel.country,
  region: hotel.region,
  image: hotel.photos[0],
}));

export function getHotel(id) {
  return hotels.find((hotel) => hotel.id === id) || null;
}

export function getRoom(hotel, roomId) {
  if (!hotel) return null;
  return hotel.rooms.find((room) => room.id === roomId) || null;
}

export function getFeaturedHotels() {
  return hotels.filter((hotel) => hotel.featured).slice(0, 3);
}
